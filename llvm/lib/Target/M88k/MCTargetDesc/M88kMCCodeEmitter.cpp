using namespace llvm;

#define DEBUG_TYPE "mccodeemitter"

STATISTIC(MCNumEmitted, "Number of MC instructions emitted");

namespace {

class M88kMCCodeEmitter : public MCCodeEmitter {
  [[maybe_unused]] const MCInstrInfo &MCII;
  MCContext &Ctx;

public:
  M88kMCCodeEmitter(const MCInstrInfo &MCII, MCContext &Ctx)
      : MCII(MCII), Ctx(Ctx) {}

  ~M88kMCCodeEmitter() override = default;

  // Override MCCodeEmitter.
  void encodeInstruction(const MCInst &MI, SmallVectorImpl<char> &CB,
                         SmallVectorImpl<MCFixup> &Fixups,
                         const MCSubtargetInfo &STI) const override;

  // Generated by TableGen.
  uint64_t getBinaryCodeForInstr(const MCInst &MI,
                                 SmallVectorImpl<MCFixup> &Fixups,
                                 const MCSubtargetInfo &STI) const;

  // Functions called by the generated function.

  /// \brief Return the binary encoding of operand. If the machine
  /// operand requires relocation, record the relocation and return zero.
  unsigned getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                             SmallVectorImpl<MCFixup> &Fixups,
                             const MCSubtargetInfo &STI) const;

  unsigned getPC16Encoding(const MCInst &MI, unsigned OpNo,
                           SmallVectorImpl<MCFixup> &Fixups,
                           const MCSubtargetInfo &STI) const;
  unsigned getPC26Encoding(const MCInst &MI, unsigned OpNo,
                           SmallVectorImpl<MCFixup> &Fixups,
                           const MCSubtargetInfo &STI) const;
};

} // end anonymous namespace

void M88kMCCodeEmitter::encodeInstruction(const MCInst &MI,
                                          SmallVectorImpl<char> &CB,
                                          SmallVectorImpl<MCFixup> &Fixups,
                                          const MCSubtargetInfo &STI) const {
  // Get instruction encoding and emit it.
  uint64_t Bits = getBinaryCodeForInstr(MI, Fixups, STI);
  ++MCNumEmitted; // Keep track of the number of emitted insns.

  // Emit bytes in big-endian.
  support::endian::write<uint32_t>(CB, Bits, endianness::big);
}

static M88k::FixupKind fixupKind(const MCExpr *Expr) {
  if (const MCSpecifierExpr *McExpr = dyn_cast<MCSpecifierExpr>(Expr)) {
    switch (McExpr->getSpecifier()) {
    default:
      llvm_unreachable("Invalid specifier");
    case M88k::S_None:
      return M88k::FK_88K_NONE;
    case M88k::S_ABS_HI:
      return M88k::FK_88K_HI;
    case M88k::S_ABS_LO:
      return M88k::FK_88K_LO;
    case M88k::S_GOT_HI:
      return M88k::FK_88K_GOT_HI;
    case M88k::S_GOT_LO:
      return M88k::FK_88K_GOT_LO;
    case M88k::S_ABDIFF_HI:
      return M88k::FK_88K_ABDIFF_HI;
    case M88k::S_ABDIFF_LO:
      return M88k::FK_88K_ABDIFF_LO;
    }
  }
  // Any other expression (e.g. 0xffff & (sym - . - 4), accepted in GNU
  // syntax mode) is a 16-bit absolute value resolved at layout time.
  return M88k::FK_88K_LO;
}

unsigned
M88kMCCodeEmitter::getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                                     SmallVectorImpl<MCFixup> &Fixups,
                                     const MCSubtargetInfo &STI) const {
  if (MO.isReg())
    return Ctx.getRegisterInfo()->getEncodingValue(MO.getReg());
  if (MO.isImm())
    return static_cast<uint64_t>(MO.getImm());

  // MO must be an expression
  assert(MO.isExpr() && "Expected MCExpr");
  const MCExpr *Expr = MO.getExpr();

  // All instructions follow the pattern that the expr has an offset of 2 from
  // the begin of the instruction.
  const uint32_t Offset = 2;
  // Push fixup (all info is contained within)
  Fixups.push_back(MCFixup::create(Offset, Expr, MCFixupKind(fixupKind(Expr))));
  return 0;
}

unsigned M88kMCCodeEmitter::getPC16Encoding(const MCInst &MI, unsigned OpNo,
                                            SmallVectorImpl<MCFixup> &Fixups,
                                            const MCSubtargetInfo &STI) const {
  const MCOperand &MO = MI.getOperand(OpNo);
  assert(MO.isImm() || MO.isExpr() && "Expected imm or MCExpr");

  const MCExpr *Expr =
      MO.isImm() ? MCConstantExpr::create(MO.getImm(), Ctx) : MO.getExpr();

  Fixups.push_back(MCFixup::create(
      0, Expr, static_cast<MCFixupKind>(M88k::FK_88K_DISP16)));
  return 0;
}

unsigned M88kMCCodeEmitter::getPC26Encoding(const MCInst &MI, unsigned OpNo,
                                            SmallVectorImpl<MCFixup> &Fixups,
                                            const MCSubtargetInfo &STI) const {
  const MCOperand &MO = MI.getOperand(OpNo);
  assert(MO.isImm() || MO.isExpr() && "Expected imm or MCExpr");

  const MCExpr *Expr =
      MO.isImm() ? MCConstantExpr::create(MO.getImm(), Ctx) : MO.getExpr();

  Fixups.push_back(MCFixup::create(
      0, Expr, static_cast<MCFixupKind>(M88k::FK_88K_DISP26)));
  return 0;
}

